/// Lấy chuỗi UI theo ngôn ngữ và key
/// Fallback: en-US → key gốc
String tr(String lang, String key) {
  return _strings[lang]?[key] ??
      _strings['en-US']?[key] ??
      key;
}

/// Lấy chuỗi UI với tham số thay thế {placeholder}
/// VD: trArgs(lang, 'words_in_db', {'n': '50'}) → "50 từ trong kho"
String trArgs(String lang, String key, Map<String, String> args) {
  var text = tr(lang, key);
  args.forEach((k, v) => text = text.replaceAll('{$k}', v));
  return text;
}

